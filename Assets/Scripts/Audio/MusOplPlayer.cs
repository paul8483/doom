        // Generated by LittleMUS lfo.py, 8 depths × 12 steps.
        private static readonly sbyte[] LfoTable =
        {
            0, 0, 1, 2, 1, 0, 0, 0, -1, -2, -1, -1,
            0, 1, 3, 4, 3, 1, 0, -1, -3, -4, -3, -2,
            0, 2, 5, 6, 5, 2, 0, -2, -5, -6, -5, -3,
            0, 3, 6, 8, 6, 3, 0, -3, -6, -8, -6, -4,
