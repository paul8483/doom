using System;

namespace Doom.Audio
{
    /// <summary>
    /// Allocation-free-after-warmup MUS sequencer driving an OPL3 device at 140 Hz.
    /// The chip is rendered at the requested output rate; this uses fractional 140 Hz
    /// scheduling instead of LittleMUS's native 49,716 Hz / 355-sample cadence.
    /// </summary>
    public sealed class MusOplPlayer
    {
        public const int TickRate = 140;
        public const int VoiceCount = 18;

        private const int KeyOn = 1 << 13;
        private const int KeyOffMask = ~KeyOn;
        private const int CentrePan = 0x30;
        private const int LeftPan = 0x10;
        private const int RightPan = 0x20;
        private const int CentreAttenuation = 6;
        private const int PanThreshold = 21;
        private const int LastPlayableNote = 95;

        private static readonly int[] Operator1 = { 0, 1, 2, 8, 9, 10, 16, 17, 18 };
        private static readonly int[] Operator2 = { 3, 4, 5, 11, 12, 13, 19, 20, 21 };

